function tintedSvg(text, accent) {
  const svg = `<svg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 120 90' preserveAspectRatio='xMidYMid slice'>
    <defs><pattern id='p' width='8' height='8' patternUnits='userSpaceOnUse' patternTransform='rotate(45)'>
      <rect width='8' height='8' fill='${accent}22'/><line x1='0' y1='0' x2='0' y2='8' stroke='${accent}44' stroke-width='1'/>
    </pattern></defs>
    <rect width='120' height='90' fill='${accent}18'/>
    <rect width='120' height='90' fill='url(#p)'/>
    <text x='60' y='50' text-anchor='middle' font-family='monospace' font-size='7' fill='${accent}' letter-spacing='0.5'>${text}</text>
  </svg>`;
  return `data:image/svg+xml;utf8,${encodeURIComponent(svg)}`;
}

// Helper: assign sequential SKUs per category, auto-place in warehouse
let _skuCounters = {};
let _locCounters = {};
function mk(cat, name, stock, notes = '', dims = {}) {
  _skuCounters[cat] = (_skuCounters[cat] || 0) + 1;
  const prefix = cat.slice(0, 2).toUpperCase();
  const id = `${prefix}-${String(_skuCounters[cat]).padStart(3, '0')}`;
  // Auto-place: zone A/B/C/D by category index, row 1-6, shelf 1-4
  const idx = CATEGORIES.findIndex(c => c.id === cat);
  const zone = ZONES[Math.floor(idx / 4) % ZONES.length];
  _locCounters[zone] = (_locCounters[zone] || 0) + 1;
  const n = _locCounters[zone];
  const row = ((n - 1) % 6) + 1;
  const shelf = (Math.floor((n - 1) / 6) % 4) + 1;
  return {
    id, sku: id, category: cat, name,
    stock, reserved: 0,
    location: { zone, row, shelf },
    dims: { w: dims.w || 0, h: dims.h || 0, d: dims.d || 0 },
    notes,
    image: tintedSvg(name.slice(0, 16), CAT_COLORS[cat]),
  };
}

